#!/usr/bin/env python3
"""Generate immutable C++ lake polygons from the supplied addon resource."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "SkyLakes.json"
OUTPUT = ROOT / "generated" / "lakes.hpp"


def number(value):
    return f"{float(value):.9f}f"


def main():
    raw = SOURCE.read_bytes()
    lakes = json.loads(raw)
    lines = ["// Generated by tools/generate_lakes.py; do not edit.",
             f"// Source SHA-256: {hashlib.sha256(raw).hexdigest()}",
             "#pragma once", "#include <cstddef>",
             "namespace mounts::generated {",
             "struct Point { float x, y, z; };",
             "struct Lake { const char* name; unsigned map; float surface, bottom; const Point* bounds; std::size_t count; };"]
    for i, lake in enumerate(lakes):
        assert len(lake["Bounds"]) >= 3
        lines.append(f"inline constexpr Point bounds{i}[] = {{")
        for p in lake["Bounds"]:
            lines.append("    {" + ", ".join(number(p[k]) for k in ("X", "Y", "Z")) + "},")
        lines.append("};")
    lines.append("inline constexpr Lake lakes[] = {")
    for i, lake in enumerate(lakes):
        lines.append("    {" + ", ".join((json.dumps(lake["Name"]), str(lake["Map"]),
                     number(lake["WaterSurface"]), number(lake["WaterBottom"]),
                     f"bounds{i}", str(len(lake["Bounds"])))) + "},")
    lines.extend(("};", "} // namespace mounts::generated", ""))
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines))
    print(f"Generated {len(lakes)} lakes: {OUTPUT}")


if __name__ == "__main__":
    main()
